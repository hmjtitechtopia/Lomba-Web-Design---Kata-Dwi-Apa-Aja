document.addEventListener("DOMContentLoaded", () => {
  const popup = document.getElementById("popupBudaya");
  const btnClose = document.getElementById("btnClosePopup");
  const popupKab = document.getElementById("popupKabupaten");
  const popupJudul = document.getElementById("popupJudul");
  const popupDesk = document.getElementById("popupDeskripsi");
  const popupImage = document.querySelector(".popup-image");
  const wilayahButtons = document.querySelectorAll(".wilayah-button");

  if (!popup || !btnClose || !popupKab || !popupJudul || !popupDesk || !popupImage) {
    return;
  }

  function bukaPopup(nama) {
    let namaAsli = "";

    for (const namaData in dataBudaya) {
      if (namaData.toLowerCase() === nama.toLowerCase()) {
        namaAsli = namaData;
        break;
      }
    }

    if (!namaAsli) {
      alert("Kabupaten tidak ditemukan.");
      return;
    }

    popupKab.textContent = "Kab. " + namaAsli;
    popupJudul.textContent = dataBudaya[namaAsli].judul;
    popupDesk.textContent = dataBudaya[namaAsli].deskripsi;
    popupImage.innerHTML = "";

    const gambar = document.createElement("img");
    gambar.src = dataBudaya[namaAsli].gambar;
    gambar.alt = dataBudaya[namaAsli].judul;
    popupImage.appendChild(gambar);

    popup.classList.add("is-open");
    popup.classList.remove("animate__fadeOut");
    popup.classList.remove("animate__fadeInUp");
    void popup.offsetWidth;
    popup.classList.add("animate__animated", "animate__fadeInUp");
    popup.setAttribute("aria-hidden", "false");
    document.dispatchEvent(new CustomEvent("wilayah:dipilih", {
      detail: { nama: namaAsli }
    }));
  }

  function tutupPopup() {
    popup.classList.remove("is-open");
    popup.classList.remove("animate__fadeInUp");
    popup.setAttribute("aria-hidden", "true");
    document.dispatchEvent(new CustomEvent("wilayah:reset"));
    wilayahButtons.forEach(button => button.classList.remove("is-active"));
  }

  btnClose.addEventListener("click", tutupPopup);

  wilayahButtons.forEach(button => {
    button.addEventListener("click", () => {
      wilayahButtons.forEach(item => item.classList.remove("is-active"));
      button.classList.add("is-active");
      bukaPopup(button.dataset.wilayah);
    });
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && popup.classList.contains("is-open")) {
      tutupPopup();
    }
  });
});